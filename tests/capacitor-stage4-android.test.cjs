const test=require('node:test'),assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'..');
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const pkg=JSON.parse(read('native-capacitor/package.json'));
const bridge=read('native-capacitor/src/native-shell.js');
const build=read('native-capacitor/scripts/build-web.mjs');
const workflow=read('.github/workflows/capacitor-android.yml');
const links=read('native-capacitor/scripts/setup-app-links.mjs');
const server=read('supabase/functions/patiyiz-push/index.ts');
const sql=read('supabase/patiyiz-native-fcm-tokens-20261024.sql');
test('Official Android camera and push plugins are in the native dependency list',()=>{
 assert.match(pkg.dependencies['@capacitor/camera'],/^\^8/);
 assert.match(pkg.dependencies['@capacitor/push-notifications'],/^\^8/);
 assert.match(bridge,/Camera\.pickImages/);
 assert.match(bridge,/Camera\.getPhoto/);
 assert.match(bridge,/input\.dispatchEvent\(new Event\('change'/);
 assert.match(bridge,/new File\(/);
 assert.match(build,/PatiyizNative\.pickPhotoForInput/);
 assert.match(build,/openComposerMediaPicker/);
 assert.match(build,/pati-story-camera/);
});
test('Native push is opt-in and only enabled when Firebase config exists',()=>{
 assert.match(bridge,/firebaseConfigured=__PATIYIZ_FCM_ENABLED__/);
 assert.match(bridge,/PushNotifications\.requestPermissions\(\)/);
 assert.match(bridge,/PushNotifications\.register\(\)/);
 assert.match(bridge,/patiyiz_native_push_tokens/);
 assert.match(bridge,/onConflict:'token'/);
 assert.match(build,/PatiyizNative\.enablePush\(me\.id,sb\)/);
 assert.match(build,/PatiyizNative\.disablePush\(\)/);
 assert.match(build,/PatiyizNative\.nativeLogout\(\)/);
 assert.match(workflow,/FIREBASE_ANDROID_GOOGLE_SERVICES_JSON_BASE64/);
 assert.match(workflow,/PATIYIZ_FCM_ENABLED=false/);
 assert.match(workflow,/client_info\?\.android_client_info\?\.package_name==='com\.patiyiz\.app'/);
 assert.doesNotMatch(bridge,/SERVICE_ROLE_KEY|private_key/);
});
test('Android App Links only accept verified Patiyiz /open URLs and approved screens',()=>{
 assert.match(links,/android:autoVerify="true"/);
 assert.match(links,/android:host="patiyiz\.com"/);
 assert.match(links,/android:pathPrefix="\/open"/);
 assert.match(bridge,/App\.addListener\('appUrlOpen'/);
 assert.match(bridge,/url\.protocol!=='https:'/);
 assert.match(bridge,/url\.hostname!=='patiyiz\.com'/);
 assert.match(bridge,/validScreens\.has\(screen\)/);
 assert.match(build,/patiyiz:native-route/);
 assert.match(build,/consumeScreen\(\)\|\|view/);
 assert.ok(fs.existsSync(path.join(root,'open/index.html')));
});
test('FCM tokens are owner-only and sending happens on server with service account',()=>{
 assert.match(sql,/enable row level security/);
 assert.match(sql,/user_id=\(select auth\.uid\(\)\)/);
 assert.match(sql,/token text not null unique/);
 assert.match(sql,/revoke all on public\.patiyiz_native_push_tokens from public,anon,authenticated/);
 assert.match(server,/FIREBASE_SERVICE_ACCOUNT_JSON/);
 assert.match(server,/oauth2\.googleapis\.com\/token/);
 assert.match(server,/fcm\.googleapis\.com\/v1\/projects/);
 assert.match(server,/from\('notifications'\)/);
 assert.match(server,/from\('push_subscriptions'\)/);
 assert.match(server,/from\('patiyiz_native_push_tokens'\)/);
 assert.match(server,/PUSH_WEBHOOK_SECRET/);
 assert.doesNotMatch(bridge,/FIREBASE_SERVICE_ACCOUNT_JSON|VAPID_PRIVATE_KEY/);
});
